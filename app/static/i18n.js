const STORE_KEY = "lire:lang";

function initialLang() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved && DICT[saved]) return saved;
  } catch { /* private mode */ }
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language || "fr"];
  return prefs.some((l) => l.toLowerCase().startsWith("fr")) ? "fr" : "en";
}

export let lang = initialLang();
let plurals = new Intl.PluralRules(lang);
const locale = () => (lang === "fr" ? "fr-FR" : "en-GB");

export function setLang(next) {
  if (!DICT[next]) return;
  lang = next;
  plurals = new Intl.PluralRules(lang);
  document.documentElement.lang = lang;
  try { localStorage.setItem(STORE_KEY, lang); } catch { /* private mode */ }
}

const fill = (text, params) => text.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));

/** Translated string; unknown keys fall back to French, then to the key itself. */
export function t(key, params = {}) {
  const value = DICT[lang][key] ?? DICT.fr[key];
  return typeof value === "string" ? fill(value, params) : key;
}

/** Counted noun: tn(3, "n.volume") gives "3 tomes" or "3 volumes". */
export function tn(n, key, withNumber = true) {
  const forms = DICT[lang][key] ?? DICT.fr[key];
  const word = plurals.select(n) === "one" ? forms.one : forms.other;
  return withNumber ? `${n} ${word}` : word;
}

export const num = (n, opts) => n.toLocaleString(locale(), opts);
export const date = (ms) => new Date(ms).toLocaleDateString(locale());

/** Translate static markup that carries data-i18n (text) or data-i18n-aria (aria-label). */
export function translateDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
}

